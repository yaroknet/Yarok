/**
 * Generates the JWT secret and the anon / service-role keys derived from it.
 *   site/.env   -> VITE_* values read by the frontend (the anon key is public by design)
 *   .env.local          -> server secrets and settings (gitignored)
 * Re-running keeps the existing secret unless --rotate is passed.
 */
import dotenv from "dotenv";
import jwt from "jsonwebtoken";
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "../..");
const localPath = path.join(root, ".env.local");
const rotate = process.argv.includes("--rotate");
const local = existsSync(localPath) ? dotenv.parse(readFileSync(localPath)) : {};

const port = local.API_PORT || "3001";
const apiUrl = local.API_URL || `http://localhost:${port}`;
const tenYears = 10 * 365 * 24 * 3600;
const iat = Math.floor(Date.now() / 1000);

// One platform: a single signing secret (and therefore one login) for every system
const secret =
  (!rotate && (local.JWT_SECRET || local.SITE_JWT_SECRET)) || randomBytes(48).toString("base64url");
const sign = (role: string) => jwt.sign({ iss: "yarok", role, iat, exp: iat + tenYears }, secret);
const anonKey = sign("anon");
const serviceKey = sign("service_role");

const writeEnv = (file: string, lines: string[]) => writeFileSync(path.join(root, file), lines.join("\n") + "\n");

writeEnv("site/.env", [
  `VITE_SUPABASE_PROJECT_ID="yarok"`,
  `VITE_SUPABASE_PUBLISHABLE_KEY="${anonKey}"`,
  `VITE_SUPABASE_URL="${apiUrl}/api/site"`,
  // API of the employees area (Yarok 360 tables)
  `VITE_EMPLOYEES_API_URL="${apiUrl}/api/ops"`,
]);

const values: Record<string, string> = {
  API_PORT: port,
  API_URL: apiUrl,
  SITE_URL: local.SITE_URL || "http://localhost:8090",
  MONGODB_URI: local.MONGODB_URI || "mongodb://127.0.0.1:27017",
  MONGODB_DB: local.MONGODB_DB || "yarok",
  JWT_SECRET: secret,
  ANON_KEY: anonKey,
  SERVICE_ROLE_KEY: serviceKey,
  ENABLE_CRON: local.ENABLE_CRON || "false",
  ENABLE_DB_TRIGGERS: local.ENABLE_DB_TRIGGERS || "false",
  WEBHOOK_DRY_RUN: local.WEBHOOK_DRY_RUN || local.WHATSAPP_DRY_RUN || "true",
};
// Keys for integrations the site's edge functions use; left empty until provided
for (const key of [
  "LOVABLE_API_KEY",
  "VAPID_PUBLIC_KEY",
  "VAPID_PRIVATE_KEY",
  "VAPID_SUBJECT",
  "EMPLOYEE_FORM_WEBHOOK_SECRET",
  "EXTERNAL_SUPABASE_URL",
  "EXTERNAL_SUPABASE_SERVICE_ROLE_KEY",
]) {
  values[key] = local[key] ?? "";
}

writeEnv(".env.local", [
  "# Local backend settings (generated by npm run setup, not committed)",
  ...Object.entries(values).map(([k, v]) => `${k}="${v}"`),
]);

console.log("Wrote .env.local and site/.env");
console.log(`API: ${apiUrl}/api/site and ${apiUrl}/api/ops`);
