tables.branches.collection = "y360_branches";

/**
 * Columns that referenced auth.users(id) in Postgres. Deleting an auth user
 * applies these the same way the FK constraints did.
 */
export const authUserReferences: AuthUserReference[] = [
  { table: "profiles", column: "user_id", onDelete: "cascade" },
  { table: "user_roles", column: "user_id", onDelete: "cascade" },
  { table: "customer_network_access", column: "user_id", onDelete: "cascade" },
  { table: "tasks", column: "assigned_to", onDelete: "set null" },
  { table: "field_reports", column: "reported_by", onDelete: "set null" },
];
